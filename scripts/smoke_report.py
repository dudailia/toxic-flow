#!/usr/bin/env python3
"""Markdown report of a smoke run, from its results/<hash>/metrics.parquet only.

Usage: uv run python scripts/smoke_report.py results/<hash> docs/smoke/<name>.md
"""

import json
import subprocess
import sys
from pathlib import Path

import polars as pl

QUEUES = ["risk_averse", "power3", "power2", "log"]
PRESENCE_FIX = "679c894"  # before it, quote presence counted steps the cap allowed both sides


def has_presence_fix(commit: str) -> bool:
    is_ancestor = ["git", "merge-base", "--is-ancestor", PRESENCE_FIX, commit]
    return subprocess.run(is_ancestor, capture_output=True).returncode == 0


def main(run_dir: Path, out: Path) -> None:
    meta = json.loads((run_dir / "meta.json").read_text())
    if meta.get("label") != "smoke":
        raise SystemExit(f"{run_dir} is not labelled smoke")
    m = pl.read_parquet(run_dir / "metrics.parquet")
    if "label" not in m.columns:  # runs from before the label column
        m = m.with_columns(label=pl.col("strategy"))
    queues = [q for q in QUEUES if q in set(m["queue"])]
    lines = [
        f"# SMOKE run {meta['config_hash']}: {', '.join(sorted(set(m['day'])))}",
        "",
        "SMOKE. One training day with placeholder parameters. It tests the harness and",
        "previews the fill-count ordering of AC2.4. It is not a result, and no parameter is",
        f"chosen from it. Config: {meta['config']}; commit {meta['commit'][:7]}; hftbacktest",
        f"{meta['hftbacktest']}. Generated by scripts/smoke_report.py from metrics.parquet.",
        "",
        "## Fills per queue model (AC2.4 preview)",
        "",
        "| Strategy | Latency | " + " | ".join(queues) + " | Fewest |",
        "|---|---|" + "---|" * len(queues) + "---|",
    ]
    for (label, latency), g in m.sort(["label", "latency"]).group_by(
        ["label", "latency"], maintain_order=True
    ):
        fills = {q: int(g.filter(pl.col("queue") == q)["fills"][0]) for q in queues}
        low = min(fills.values())
        # A tie shows every model at the minimum, so a shared minimum is visible.
        fewest = (
            " = ".join(q for q in queues if fills[q] == low) if len(queues) > 1 else "(one model)"
        )
        lines.append(
            f"| {label} | {latency} | "
            + " | ".join(str(fills[q]) for q in queues)
            + f" | {fewest} |"
        )
    lines += ["", "## Per cell", ""]
    if not has_presence_fix(meta["commit"]):
        lines += [
            f"Quote presence below is not valid: this run predates commit {PRESENCE_FIX}, and",
            "until then a step counted as quoted whenever the inventory cap allowed both",
            "sides, whether or not orders rested in the book. Fills, PnL, BEF and markouts",
            "are not affected.",
            "",
        ]
    lines += [
        "| Strategy | Queue | Latency | Fills | BEF bp | Net at standard maker USDT | "
        "Quote presence | Markout 10 s bp | Max inventory (order sizes) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in m.sort(["label", "queue", "latency"]).iter_rows(named=True):
        lines.append(
            f"| {r['label']} | {r['queue']} | {r['latency']} | {r['fills']} | "
            f"{r['break_even_fee_bps']:.3f} | {r['net_pnl_standard_maker']:.2f} | "
            f"{r['quote_presence']:.3f} | {r['mean_markout_10s_bps']:.3f} | {r['max_inventory_lots']} |"
        )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(out)


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
